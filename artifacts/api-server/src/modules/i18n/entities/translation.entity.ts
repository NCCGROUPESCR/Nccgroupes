import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';

@Entity('i18n_translations')
@Index(['languageCode', 'namespace', 'key'], { unique: true })
export class Translation {
  @PrimaryGeneratedColumn()
  id: number;

  /** BCP-47 code matching i18n_languages.code */
  @Index()
  @Column({ type: 'varchar', length: 10 })
  languageCode: string;

  /** Logical grouping: "nav", "footer", "auth", "landing", etc. */
  @Index()
  @Column({ type: 'varchar', length: 60 })
  namespace: string;

  /** Dot-free key within the namespace, e.g. "log_in" */
  @Column({ type: 'varchar', length: 255 })
  key: string;

  /** Translated text; null means fall back to English */
  @Column({ type: 'text', nullable: true })
  value: string | null;

  /** True when generated by AI rather than hand-edited */
  @Column({ default: false })
  isAIGenerated: boolean;

  @CreateDateColumn()
  createdAt: Date;

  @UpdateDateColumn()
  updatedAt: Date;
}
